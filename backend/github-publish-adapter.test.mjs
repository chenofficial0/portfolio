import assert from "node:assert/strict";
import {makeGitHubPublishAdapter} from "./src/github-publish-adapter.js";
const head="1".repeat(40),tree="2".repeat(40),blob="3".repeat(40),commit="4".repeat(40);
const operations=[];
const mock=async(url,options)=>{
 const u=new URL(url);operations.push({path:u.pathname+u.search,method:options.method,body:options.body?JSON.parse(options.body):null});
 if(u.pathname.endsWith("/git/ref/heads/main"))return response({object:{sha:head}});
 if(u.pathname.endsWith("/git/commits/"+head))return response({tree:{sha:tree}});
 if(u.pathname.includes("/contents/assets/uploads/"))return response({},404);
 if(u.pathname.endsWith("/git/blobs"))return response({sha:blob});
 if(u.pathname.endsWith("/git/trees"))return response({sha:tree});
 if(u.pathname.endsWith("/git/commits"))return response({sha:commit});
 if(u.pathname.endsWith("/git/refs/heads/main"))return response({object:{sha:commit}});
 return response({},404);
};
const response=(data,status=200)=>({ok:status>=200&&status<300,status,json:async()=>data});
const a=makeGitHubPublishAdapter("SYNTHETIC_TOKEN",{fetchImpl:mock});
assert.equal(await a.getMainSha(),head);
assert.equal(await a.getMainTreeSha(head),tree);
const path="assets/uploads/chen-profile-2026-11-12-mragG3nnw0NgdAUw.jpg";
assert.equal(await a.getPathSha(head,path),null);
assert.equal(await a.createBlob(new Uint8Array([1,2,3]),"base64"),blob);
assert.equal(await a.createBlob(new TextEncoder().encode('{"hello":true}'),"utf-8"),blob);
assert.equal(await a.createTree(tree,[{path:"content/site.json",mode:"100644",type:"blob",sha:blob}]),tree);
assert.equal(await a.createCommit({parentSha:head,treeSha:tree,message:"Restore previous CHEN public site"}),commit);
assert.equal(await a.updateMainRef(commit,{force:false}),commit);
assert.equal(operations.at(-1).body.force,false);
assert.ok(operations.every(o=>o.path.startsWith("/repos/chenofficial0/portfolio/")));
assert.ok(operations.every(o=>["GET","POST","PATCH"].includes(o.method)));
await assert.rejects(a.updateMainRef(commit,{force:true}),/FORCE_PUSH_FORBIDDEN/);
await assert.rejects(a.getPathSha(head,"../.github/workflows/hijack.yml"),/UNSAFE_PUBLIC_PATH/);
await assert.rejects(a.createTree(tree,[{path:".github/workflows/x.yml",mode:"100644",type:"blob",sha:blob}]),/UNSAFE_GIT_RELEASE_TREE/);
await assert.rejects(a.createCommit({parentSha:head,treeSha:tree,message:"malicious"}),/UNSAFE_GIT_COMMIT_MESSAGE/);
assert.throws(()=>makeGitHubPublishAdapter(""),/GITHUB_TOKEN_UNAVAILABLE/);
console.log("PASS: GitHub publication adapter restricts paths, commit messages and non-force branch updates.");

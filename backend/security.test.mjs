import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import worker from './src/worker.js';
const origin='https://studio-test.example';
const kv=new Map();
const env={PUBLIC_API_ORIGIN:origin,GITHUB_CLIENT_ID:'test-client',STUDIO_KV:{get:async k=>kv.get(k)||null,put:async(k,v)=>kv.set(k,v),delete:async k=>kv.delete(k)}};
const req=(path,init={})=>worker.fetch(new Request(origin+path,init),env);
assert.equal((await req('/api/content')).status,401);
assert.equal((await req('/api/content',{method:'PUT',headers:{origin},body:'{}'})).status,401);
assert.equal((await req('/api/logout',{method:'POST',headers:{origin:'https://evil.example'}})).status,403);
assert.equal((await req('/auth/callback?state=bad&code=bad')).status,403);
assert.deepEqual(await (await req('/api/session')).json(),{authenticated:false});
const login=await req('/auth/login');
assert.equal(login.status,302);
assert.match(login.headers.get('set-cookie'),/HttpOnly; Secure; SameSite=Lax/);
const loc=new URL(login.headers.get('location'));
assert.equal(loc.origin,'https://github.com');
assert.equal(loc.searchParams.get('redirect_uri'),origin+'/auth/callback');
assert.ok(loc.searchParams.get('state').length>=40);
assert.equal(kv.size,1);
// Create a valid encrypted editor session to exercise the server-side write gate.
const bytes=crypto.getRandomValues(new Uint8Array(32));
env.SESSION_ENCRYPTION_KEY=Buffer.from(bytes).toString('base64');
const aes=await crypto.subtle.importKey('raw',bytes,'AES-GCM',false,['encrypt']);
const iv=crypto.getRandomValues(new Uint8Array(12));
const payload={login:'chenofficial0',csrf:'test-csrf',token:'FAKE_TEST_TOKEN',exp:Date.now()+60000};
const encrypted=await crypto.subtle.encrypt({name:'AES-GCM',iv},aes,new TextEncoder().encode(JSON.stringify(payload)));
const sid='test-session';
const hashed=Buffer.from(await crypto.subtle.digest('SHA-256',new TextEncoder().encode(sid))).toString('base64url');
kv.set('session:'+hashed,Buffer.from(iv).toString('base64')+'.'+Buffer.from(encrypted).toString('base64'));
const denied=await req('/api/content',{method:'PUT',headers:{origin,cookie:'chen_session='+sid,'x-chen-csrf':'test-csrf'},body:'{}'});
assert.equal(denied.status,403);
assert.match((await denied.json()).error,/writes are disabled/);
assert.ok(!JSON.stringify(await (await req('/api/session',{headers:{cookie:'chen_session='+sid}})).json()).includes('FAKE_TEST_TOKEN'));
const source=readFileSync(new URL('./src/worker.js',import.meta.url),'utf8');
assert.ok(source.includes('env.ENABLE_CONTENT_WRITES!=="true"'));
assert.ok(!source.includes('branch:"main"'));
assert.ok(!source.includes('?ref=main'));
assert.equal((await worker.fetch(new Request('https://wrong.example/api/session'),env)).status,503);
console.log('PASS: unauthenticated writes, hostile origin, invalid OAuth state, session privacy, OAuth redirect/cookie, origin mismatch; write gate and branch isolation checked.');
